"""Навчальний приклад: зміна яскравості одного пікселя.

Контракт: pixel — звичайне ціле число Python від 0 до 255,
delta — ціла зміна; результат обмежений діапазоном [0, 255].
Поведінка для аргументів поза контрактом цим прикладом не задається.
"""


def brighten(pixel: int, delta: int) -> int:
    """Повернути яскравість після зміни з насиченням на обох межах."""
    return max(0, min(255, pixel + delta))
